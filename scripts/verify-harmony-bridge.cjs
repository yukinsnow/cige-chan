const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const calls = [];
const window = { CigeHarmony: {request(...args){calls.push(args)}} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'harmony-bridge.js'),'utf8'),{window,Map,Promise,Error,JSON});
(async()=>{
  const invoke = window.__TAURI__.core.invoke;
  const text=invoke('open_text',{exts:['txt']});
  assert.equal(calls[0][1],'open_text');
  window.__cigeNativeReply(calls[0][0],true,JSON.stringify({name:'song.txt',contents:'你好'}));
  assert.equal((await text).contents,'你好');
  const cancel=invoke('save_text',{contents:'草稿'});
  window.__cigeNativeReply(calls[1][0],true,'null');assert.equal(await cancel,null);
  const binary=invoke('open_binary',{});
  window.__cigeNativeReply(calls[2][0],true,'[0,127,255]');assert.deepEqual(await binary,[0,127,255]);
  const failure=invoke('save_binary',{});
  window.__cigeNativeReply(calls[3][0],false,'disk full');await assert.rejects(failure,/disk full/);
  const malformed=invoke('open_text',{});
  window.__cigeNativeReply(calls[4][0],true,'invalid json');await assert.rejects(malformed);
  window.CigeHarmony.request=()=>{throw Error('bridge unavailable')};
  await assert.rejects(invoke('open_text',{}),/bridge unavailable/);
  window.__cigeNativeReply('unknown',true,'null');
  const staged=path.join(root,'src-harmony/entry/src/main/resources/rawfile/web');
  for(const file of ['ai.js','i18n.js','feature.html']) assert.deepEqual(fs.readFileSync(path.join(staged,file)),fs.readFileSync(path.join(root,'src',file)));
  const html=fs.readFileSync(path.join(staged,'index.html'),'utf8');
  assert.ok(html.includes('<script src="harmony-bridge.js"></script>'));
  assert.equal(html.replace('\n<script src="harmony-bridge.js"></script>',''),fs.readFileSync(path.join(root,'src/index.html'),'utf8'));
  console.log('PASS HarmonyOS bridge: text, cancellation, binary, errors, malformed replies, unavailable bridge and unchanged staged editor');
})().catch(e=>{console.error(e);process.exitCode=1});
